/** Tests a publication gate, not a training release. Nothing is written under public/. */
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { copyFile, mkdir, mkdtemp, readFile, rename, rm, symlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import test from 'node:test'
import { SOURCE_PINS, TRAINED_FORMAT } from '../src/trained/contract.ts'
import { verifyRelease } from './verify-release.mjs'

const source = fileURLToPath(new URL('..', import.meta.url))
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex')
const identity = (label) => hash(label)
const json = (path, data) => writeFile(path, JSON.stringify(data) + '\n')
const modelId = 'reproduction-v1'
const manifests = process.env.BROWSER_QA_FIXTURE_DIR
const mjlabLicense = process.env.BROWSER_QA_MJLAB_LICENSE

async function sandbox(fn) {
  const root = await mkdtemp(join(tmpdir(), 'release-gate-test-'))
  try {
    const pub = join(root, 'public')
    const models = join(pub, 'models')
    const registry = join(models, 'releases.json')
    await mkdir(models, { recursive: true })
    await json(registry, { schema_version: 1, active: null })
    return await fn({ pub, models, registry })
  } finally { await rm(root, { recursive: true, force: true }) }
}

test('the unpublished registry contains no model assets', () => sandbox(async ({ pub, models }) => {
  assert.equal(await verifyRelease(pub), null)
  await mkdir(join(models, modelId))
  await assert.rejects(verifyRelease(pub), /unexpected or missing files/)
}))

test('missing registry or active directory is rejected', () => sandbox(async ({ pub, registry }) => {
  await rm(registry)
  await assert.rejects(verifyRelease(pub), /ENOENT/)
  await json(registry, { schema_version: 1, active: modelId })
  await assert.rejects(verifyRelease(pub), /unexpected or missing files/)
}))

test('a synthetic, malformed, or symlinked release is rejected before loading weights', () => sandbox(async ({ pub, models, registry }) => {
  await json(registry, { schema_version: 1, active: 'synthetic-not-trained' })
  await assert.rejects(verifyRelease(pub), /QA fixture/)
  await json(registry, { schema_version: 1, active: '../bad' })
  await assert.rejects(verifyRelease(pub), /trained release/)
  await json(registry, { schema_version: 1, active: modelId })
  await symlink(pub, join(models, modelId))
  await assert.rejects(verifyRelease(pub), /real directory/)
}))

// Optional full-size fixture generated by training/test_browser_export.py
// --g1-scene. Its audit is forged *for testing joins only*, in a temp directory.
// The gate validates internal consistency and runnable artifacts; the on-AIR
// audit/export process remains the authority for where the real weights came from.
test('full structural audit and runnable assets; invalid provenance and altered assets fail', {
  skip: !manifests || !mjlabLicense,
}, () => sandbox(async ({ pub, models, registry }) => {
  await json(registry, { schema_version: 1, active: modelId })
  const release = join(models, modelId)
  const evidence = join(pub, 'reproduction')
  await mkdir(release)
  await mkdir(evidence)
  const manifestFile = join(release, 'manifest.json')
  const auditFile = join(evidence, 'full-audit.json')
  const preflightFile = join(evidence, 'preflight.json')
  const preflight = JSON.parse(await readFile(join(source, 'public', 'reproduction', 'preflight.json'), 'utf8'))
  preflight.dataset.air_sha256_verified = true
  await json(preflightFile, preflight)
  const dataset = preflight.dataset.sha256
  const artifactFile = join(release, 'actor.onnx')
  await copyFile(join(manifests, 'actor.onnx'), artifactFile)
  await copyFile(join(manifests, 'scene.mjbpack'), join(release, 'scene.mjbpack'))
  await copyFile(mjlabLicense, join(release, 'mjlab-LICENSE.txt'))
  await copyFile(join(source, 'training', 'licenses', 'Unitree-BSD-3-Clause.txt'), join(release, 'Unitree-LICENSE.txt'))
  await writeFile(join(release, 'ATTRIBUTION.md'), '# SuperMimic browser policy\n\n' +
    'Training data includes Motion Data by [Bones Studio](https://bones.studio/). ' +
    'Use of the underlying dataset is subject to the BONES Motion Capture Dataset License Agreement.\n\n' +
    'The scene is compiled from the pinned [mjlab source](https://github.com/HybridRobotics/mjlab_research), ' +
    'licensed under Apache-2.0; see mjlab-LICENSE.txt. The model contains [Unitree G1 robot geometry]' +
    '(https://github.com/unitreerobotics/unitree_mujoco/tree/1eb6642e3f3fdfb7fb13a9794fd6a2dd93ea0e7d/unitree_robots/g1), ' +
    'BSD-3-Clause; see Unitree-LICENSE.txt.\n')
  const artifacts = {}
  for (const name of ['actor.onnx', 'scene.mjbpack', 'mjlab-LICENSE.txt', 'Unitree-LICENSE.txt', 'ATTRIBUTION.md']) {
    const bytes = await readFile(join(release, name))
    artifacts[name] = { bytes: bytes.length, sha256: hash(bytes) }
  }
  const metrics = { evaluated_clips: 40, completed_clips: 35, failed_clips: 5, completion_rate: 35 / 40,
    evaluated_steps: 90_000, reference_steps: 100_000, mean_normalized_return: 0.8, mean_root_position_error_m: 0.3,
    mean_heading_aligned_body_position_error_m: 0.2 }
  const sha = Object.fromEntries(['actor.pt', 'world_model.pt', 'run-config.json', 'training_state.pt', 'critic.pt'].map((key) => [key, identity(key)]))
  const reproduction = identity('synthetic-source-identity').slice(0, 40)
  const checkpoint_archive_sha256 = identity('checkpoint')
  const checkpoint_archive_bytes = 123456789
  const job = (job_id) => ({ job_id, state: 'COMPLETED', exit_code: '0:0', allocated_gpus: 1 })
  const full = {
    schema_version: 1, phase: 'full', source_commits: SOURCE_PINS, reproduction_commit: reproduction,
    dataset_sha256: dataset, motion_archive_sha256: identity('filtered motions'), code_sha256: identity('code'),
    environment_sha256: identity('environment'), allocations: [job('101')], num_envs: 4096, checkpoint_step: 320_000,
    checkpoint_job_id: '101', checkpoint_archive_sha256, checkpoint_archive_bytes, checkpoint_artifact_sha256: sha,
    retained_checkpoints: Array.from({ length: 10 }, (_, i) => ({ step: (i + 1) * 32_000,
      archive_sha256: i === 9 ? checkpoint_archive_sha256 : identity(`milestone ${i}`), archive_bytes: checkpoint_archive_bytes })),
    motions: { clips: 129_514, frames: 1_234_567, fps: 50 },
    motion_manifest: { selection: 'explicit-allowlist', sha256: identity('packed manifest'), clipset_sha256: identity('clip set'),
      clips: 129_514, frames: 1_234_567, input_fps: 120, fps: 50, selection_id: 'supermimic-v3-authors-manifest',
      approximate: false, allowlist_sha256: identity('allowed clip set') },
    outputs_archive_sha256: identity('run logs'),
    verified_checks: ['slurm_terminal_state', 'job_status', 'success_marker', 'source_pins', 'dataset_checksum',
      'packed_motion_checksum', 'target_step', 'checkpoint_archive_integrity', 'milestone_retention', 'held_out_evaluation'],
    held_out_evaluation_verified: true,
    held_out_evaluation: { ...job('102'), metrics, metrics_sha256: identity('private metrics'), outputs_archive_sha256: identity('eval logs'),
      suite: { source: 'lvhaidong/LAFAN1_Retargeting_Dataset', revision: 'ce1572906efe6157840e8474d5a0d7aa87481e74',
        archive_sha256: identity('heldout'), clip_manifest_sha256: hash(await readFile(join(source, 'training', 'lafan1_g1_eval_manifest.tsv'))), clips: 40 } },
  }
  const manifest = {
    format: TRAINED_FORMAT, model_id: modelId, task: 'SuperMimic-GenCoord-G1', dataset_sha256: dataset, checkpoint_step: 320_000,
    source_commits: { ...SOURCE_PINS, reproduction }, checkpoint_actor_sha256: sha['actor.pt'],
    checkpoint_world_model_sha256: sha['world_model.pt'], metrics, artifacts,
    policy: { state_dim: 68, goal_dim: 640, action_dim: 29, goal_frames: 10, goal_stride: 5,
      ...JSON.parse(await readFile(join(manifests, 'parity.json'), 'utf8')) },
    robot: JSON.parse(await readFile(join(manifests, 'robot.json'), 'utf8')),
  }
  await json(manifestFile, manifest)
  await assert.rejects(verifyRelease(pub), /full-audit\.json/)
  await json(auditFile, full)
  assert.equal(await verifyRelease(pub), modelId)

  const curve = {
    schema_version: 1,
    coverage: { scope: 'final-allocation-only', resumed_from_iterations: 319_960, log_interval: 10,
      first_logged_step: 319_961, last_logged_step: 319_991, logged_rows: 4 },
    metrics_jsonl_sha256: identity('bounded private metrics'),
    series: [{ id: 'train-episode-reward', observation_count: 2, points: [{ step: 319_961, value: -2 }, { step: 319_991, value: 4 }] },
      { id: 'train-world-model-loss', observation_count: 1, points: [{ step: 319_981, value: 0.05 }] }],
  }
  await json(auditFile, { ...full, learning_curves: curve })
  assert.equal(await verifyRelease(pub), modelId)
  const { held_out_evaluation: _evaluation, ...trainingOnly } = full
  trainingOnly.held_out_evaluation_verified = false
  trainingOnly.verified_checks = full.verified_checks.filter((check) => check !== 'held_out_evaluation')
  await json(registry, { schema_version: 1, active: null })
  const staged = join(pub, 'unpublished-release-temp')
  await rename(release, staged)
  await json(auditFile, { ...trainingOnly, learning_curves: curve })
  assert.equal(await verifyRelease(pub), null)
  await json(auditFile, { ...trainingOnly, learning_curves: { ...curve, coverage: { ...curve.coverage, private_path: 'not a public field' } } })
  await assert.rejects(verifyRelease(pub), /coverage is invalid/)
  await json(auditFile, { ...trainingOnly, learning_curves: { ...curve, coverage: { ...curve.coverage, logged_rows: 3 } } })
  await assert.rejects(verifyRelease(pub), /row count/)
  await json(auditFile, { ...trainingOnly, learning_curves: { ...curve, coverage: {
    ...curve.coverage, first_logged_step: 319_971, logged_rows: 3,
  } } })
  await assert.rejects(verifyRelease(pub), /coverage row count/)
  await json(auditFile, { ...trainingOnly, learning_curves: { ...curve, series: [...curve.series, curve.series[1]] } })
  await assert.rejects(verifyRelease(pub), /series ID, ordering or point count/)
  await json(auditFile, { ...trainingOnly, learning_curves: { ...curve, series: [{ ...curve.series[0], observation_count: 1,
    points: [{ step: 319_992, value: 1 }] }] } })
  await assert.rejects(verifyRelease(pub), /logged step cadence/)
  await json(auditFile, { ...trainingOnly, learning_curves: { ...curve, series: [{ ...curve.series[1],
    points: [{ step: 319_981, value: -1 }] }] } })
  await assert.rejects(verifyRelease(pub), /bounded aggregate/)
  await json(auditFile, { ...trainingOnly, learning_curves: { ...curve, coverage: {
    ...curve.coverage, resumed_from_iterations: 320_000, first_logged_step: null, last_logged_step: null, logged_rows: 0,
  }, series: [], metrics_jsonl_sha256: null } })
  assert.equal(await verifyRelease(pub), null)
  await json(auditFile, { ...trainingOnly, held_out_evaluation: { metrics } })
  await assert.rejects(verifyRelease(pub), /Full audit must verify/)
  await json(auditFile, trainingOnly)
  await json(preflightFile, { ...preflight, dataset: { ...preflight.dataset, air_sha256_verified: false } })
  await assert.rejects(verifyRelease(pub), /verified locally and after AIR transfer/)
  await json(preflightFile, preflight)
  await rename(staged, release)
  await json(registry, { schema_version: 1, active: modelId })
  await assert.rejects(verifyRelease(pub), /held-out evaluation before model publication/)
  await json(auditFile, full)

  await json(preflightFile, { ...preflight, dataset: { ...preflight.dataset, air_sha256_verified: false } })
  await assert.rejects(verifyRelease(pub), /verified locally and after AIR transfer/)
  await json(preflightFile, preflight)

  await json(auditFile, { ...full, checkpoint_step: 319_999 })
  await assert.rejects(verifyRelease(pub), /exact 320,000-step/)
  await json(auditFile, { ...full, motion_manifest: { ...full.motion_manifest, approximate: true } })
  await assert.rejects(verifyRelease(pub), /exact or approximate cohort/)
  await json(auditFile, { ...full, motion_manifest: { ...full.motion_manifest, fps: 60 } })
  await assert.rejects(verifyRelease(pub), /sample rates/)
  await json(auditFile, { ...full, motion_manifest: { ...full.motion_manifest, approximate: true,
    selection_id: 'supermimic-v3-appendix-e-approx-v1' } })
  assert.equal(await verifyRelease(pub), modelId)
  await json(auditFile, { ...full, held_out_evaluation: { ...full.held_out_evaluation, suite: { ...full.held_out_evaluation.suite, archive_sha256: dataset } } })
  await assert.rejects(verifyRelease(pub), /independent corpus/)
  await json(auditFile, full)
  await json(manifestFile, { ...manifest, checkpoint_actor_sha256: identity('different checkpoint') })
  await assert.rejects(verifyRelease(pub), /not bound to the audited final checkpoint/)
  await json(manifestFile, { ...manifest, metrics: { ...metrics, mean_normalized_return: 0.9 } })
  await assert.rejects(verifyRelease(pub), /exactly match the audited/)
  await json(manifestFile, manifest)

  const backup = join(pub, 'unpublished-actor.test')
  await rename(artifactFile, backup)
  await writeFile(artifactFile, 'not ONNX')
  await assert.rejects(verifyRelease(pub), /mismatched artifact size\/hash/)
  const dummy = await readFile(artifactFile)
  await json(manifestFile, { ...manifest, artifacts: { ...artifacts, 'actor.onnx': { bytes: dummy.length, sha256: hash(dummy) } } })
  await assert.rejects(verifyRelease(pub), /failed|invalid|parse/i)
  await rename(backup, artifactFile)
  await json(manifestFile, manifest)

  await writeFile(join(release, 'world_model.pt'), 'disallowed artifact')
  await assert.rejects(verifyRelease(pub), /unexpected or missing files/)
}))
